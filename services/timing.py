import time # Импортируем модуль time для работы со временем


def timer(func):
    """
        ДЕКОРАТОР: Функция, которая оборачивает другую функцию для добавления дополнительного функционала.
        Назначение: Измеряет время выполнения декорируемой функции и выводит результат в консоль.
        Параметры:
        ----------
        func : callable
            Функция, которую нужно обернуть (декорировать).
            Может быть любой функцией, время выполнения которой нужно измерить.
        Возвращает:
        -----------
        callable
            Функцию-обертку (wrapper), которая при вызове выполнит:
            1. Замер времени до выполнения исходной функции
            2. Выполнение исходной функции
            3. Замер времени после выполнения
            4. Вывод результата в консоль
            5. Возврат результата исходной функции
        """
    def wrapper(*args, **kwargs):
        """
                ФУНКЦИЯ-ОБЕРТКА: Внутренняя функция, которая заменяет исходную функцию.
                *args : tuple
                    Позиционные аргументы, переданные в декорируемую функцию
                **kwargs : dict
                    Именованные аргументы, переданные в декорируемую функцию
                Возвращает результат выполнения исходной функции
                """
        # 1. ФИКСАЦИЯ ВРЕМЕНИ СТАРТА
        # time.time() возвращает текущее время в секундах с начала эпохи (Unix timestamp)
        # Запоминаем момент начала выполнения функции
        start = time.time()
        # 2. ВЫПОЛНЕНИЕ ИСХОДНОЙ ФУНКЦИИ
        # Вызываем исходную функцию с переданными ей аргументами
        # Результат ее работы сохраняем в переменную result
        # Этот вызов может занять разное время в зависимости от сложности функции
        result = func(*args, **kwargs)  # Здесь func должна быть функцией
        # 3. ФИКСАЦИЯ ВРЕМЕНИ ФИНИША И РАСЧЕТ ДЛИТЕЛЬНОСТИ
        # Вычитаем время старта из текущего времени, получаем длительность выполнения
        # :.2f - форматирует число с плавающей точкой до 2 знаков после запятой
        print(f"Время: {time.time() - start:.2f} сек")
        # 4. ВОЗВРАТ РЕЗУЛЬТАТА
        # Возвращаем результат выполнения исходной функции
        # Без этого исходная функция не смогла бы передать свой результат вызывающему коду
        return result
    # 5. ВОЗВРАТ ФУНКЦИИ-ОБЕРТКИ
    # Возвращаем функцию wrapper, которая ЗАМЕНЯЕТ исходную функцию
    # Теперь при вызове func() будет вызываться не оригинальная функция, а обертка
    return wrapper
